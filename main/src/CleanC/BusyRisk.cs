namespace CleanC;

/// <summary>
/// 长任务的风险等级。决定「处理中」遮罩怎么画、能不能取消、能不能关窗口。
///
/// 分级原则只有一句话：**中断这个操作，会不会留下无法自动恢复的坏状态。**
/// </summary>
public enum BusyRisk
{
    /// <summary>
    /// 只读或可安全中断（扫描、分析、测算）。打断只损失一点时间：遮罩给「取消」，
    /// 直接关窗口也不拦——否则就变成"程序卡住还不让关"的糟糕体验。
    /// </summary>
    Safe,

    /// <summary>
    /// 会改磁盘上的文件，但停下来不会留下坏状态（清理临时文件、删除开发缓存）。
    /// 可以取消；关窗口前先确认一次，把"会中断"讲清楚。
    /// </summary>
    Interrupt,

    /// <summary>
    /// 中断后**可能留下无法自动恢复的状态**（分区收缩/删除/扩容、正在运行的卸载程序）。
    /// 遮罩显示红色警示、不提供取消按钮，并且**拒绝关闭窗口**，直到操作完成。
    /// </summary>
    Critical
}
